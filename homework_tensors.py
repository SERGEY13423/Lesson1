def task_1_2_operations():
    """1.2 Операции над тензорами: транспонирование, умножения, суммы."""
    print("--- 1.2 Операции с тензорами ---")

    # Создаем тензоры для демонстрации
    A = torch.rand(3, 4)
    B = torch.rand(4, 3)
    print("Матрица A (3x4):\n", A)
    print("Матрица B (4x3):\n", B)

    # Транспонирование A (было 3x4 -> стало 4x3)
    A_t = A.t()  # или A.T
    print("\nТранспонированная A (4x3):\n", A_t)

    # Матричное умножение A (3x4) @ B (4x3) -> результат (3x3)
    # Используем оператор @ или функцию torch.matmul
    matmul_res = torch.matmul(A, B)
    print("\nМатричное умножение (A @ B) (3x3):\n", matmul_res)

    # Поэлементное умножение A и транспонированного B
    # B имеет размер 4x3, его транспонированная версия B.t() имеет размер 3x4.
    # Так как размеры A (3x4) и B.t() (3x4) совпадают, их можно умножить поэлементно:
    elementwise_res = A * B.t()
    print("\nПоэлементное умножение A * B.t() (3x4):\n", elementwise_res)

    # Сумма всех элементов тензора A
    total_sum = A.sum()
    print(f"\nСумма всех элементов тензора A: {total_sum.item():.4f}\n")


def task_1_3_indexing():
    """1.3 Индексация и срезы 3D-тензора 5x5x5."""
    print("--- 1.3 Индексация и срезы ---")

    # Создаем 3D-тензор размером 5x5x5
    # Заполним его упорядоченными числами, чтобы срезы было наглядно видно
    T = torch.arange(125).reshape(5, 5, 5)
    print(f"Форма тензора T: {T.shape}")

    # Первая строка: фиксируем первую 2D-матрицу (0) и ее первую строку (0)
    first_row = T[0, 0, :]
    print("\n1) Первая строка (T[0, 0, :]):\n", first_row)

    # Последний столбец: индекс -1 означает последний элемент
    last_col = T[0, :, -1]
    print("\n2) Последний столбец первой матрицы (T[0, :, -1]):\n", last_col)

    # Подматрица 2x2 из центра:
    # Индексы от 0 до 4, центр — это индексы 1, 2, 3. 
    # Возьмем центральный срез 2x2 (индексы 1:3 или 2:4)
    center_submatrix = T[2, 1:3, 1:3]
    print("\n3) Центральная подматрица 2x2 центрального слоя T[2, 1:3, 1:3]:\n", center_submatrix)

    # Все элементы с четными индексами (шаг 2 по всем измерениям)
    even_elements = T[::2, ::2, ::2]
    print("\n4) Элементы с четными индексами (формат среза [::2, ::2, ::2]):\n", even_elements)
    print()


def task_1_4_shapes():
    """1.4 Преобразование формы (reshape) тензора из 24 элементов."""
    print("--- 1.4 Работа с формами ---")

    # 24 элемента: 0..23
    base_tensor = torch.arange(24)
    print("Базовый плоский тензор:\n", base_tensor)

    # Изменяем форму. Произведение всех измерений обязано равняться 24!
    forms = [
        (2, 12),  # 2 * 12 = 24
        (3, 8),  # 3 * 8 = 24
        (4, 6),  # 4 * 6 = 24
        (2, 3, 4),  # 2 * 3 * 4 = 24
        (2, 2, 2, 3)  # 2 * 2 * 2 * 3 = 24
    ]

    for shape in forms:
        reshaped = base_tensor.reshape(shape)
        print(f"Форма {shape}: shape={reshaped.shape}, numel={reshaped.numel()}")


